"""Что НЕ является секретом: плейсхолдеры и адреса на своей машине.

Сателлит `security_scan` (фасад импортирует отсюда `looks_like_placeholder` и `is_loopback_dsn`).
Появился не из вкуса к дроблению: после разбора ложных блокировок (#1138) сканер перешагнул порог
монолита в 700 строк — ратчет размера модуля сказал об этом до слияния.

ЗДЕСЬ ТОЛЬКО ТО, ЧТО ГОВОРИТ «ЭТО НЕ СЕКРЕТ» ПО САМОМУ ЗНАЧЕНИЮ. Признак «где лежит» сюда не
относится намеренно: код в документации не исполняется, а пароль в документации — всё ещё утёкший
пароль (см. сторож `test_security_scan_secret_false_blocks`).

Своей точки входа у сателлита нет осознанно: он обслуживает сканер, а не запускается сам.
"""
from __future__ import annotations

import re

# Плейсхолдеры и ссылки на env — не секрет.
#
# СПИСОК БЫЛ АНГЛОЯЗЫЧНЫМ И ASCII-ONLY (#1138). Класс `[a-z_]` физически не мог сматчить кириллицу,
# поэтому «ПАРОЛЬ» в инструкции по развёртыванию читался как утечка; слова `pass`/`password` в списке
# тоже не было, хотя `user:pass@host` — самая частая форма плейсхолдера в строке подключения.
# Вердикт независимого судьи 24.09.2026 по реальному продукту: 5 находок из 17 — ровно этот класс.
# ЗАГЛУШКА — ЭТО ВСЁ ЗНАЧЕНИЕ, А НЕ БУКВЫ ВНУТРИ НЕГО (#1150).
#
# Прежде `your|example|changeme|placeholder|x{6,}` искались ВХОЖДЕНИЕМ, поэтому настоящие пароли, в
# которых эти буквы просто встретились, молчали: `S3cretexample1`, `Youre4Me99xz`, `xxxxxxA9zQ`.
# Это пропуск утечки, а не лишний шум, — самый дорогой род ошибки для проверки секретов.
#
# ПЕРВАЯ ПОПЫТКА ПОЧИНКИ БЫЛА СЛАБЕЕ, И ЭТО НАШЛО НЕЗАВИСИМОЕ РЕВЬЮ. Опознание «слово с границами»
# закрывало только случай «буквы склеены вплотную»: `S3cret_changeme_9` и `Pr0d-your-K3y` оставались
# непойманными, потому что там слово-заглушка отделено разделителем ВНУТРИ настоящего пароля.
#
# ПРИЗНАК, КОТОРЫЙ РАБОТАЕТ: значение ЦЕЛИКОМ разбирается на словарные слова, цифры и разделители —
# и хотя бы одно из слов собственно заглушечное. У настоящего секрета есть материал высокой
# энтропии (`S3cret`, `Pr0d`, `9Qz`), который в словарь не попадает, поэтому разбор не сходится и
# значение остаётся находкой. Словарь при этом не обязан быть полным: непокрытое слово делает
# значение находкой, то есть ошибка словаря ведёт к ЛИШНЕМУ вниманию, а не к пропуску.
#
# ТРЕБОВАНИЕ «ХОТЯ БЫ ОДНО СЛОВО ИЗ ЯДРА» — НЕ УКРАШЕНИЕ. Без него значение `MySecretPassword123`
# разбирается нацело и было бы прощено, хотя это настоящий (слабый) пароль, а не заглушка.
# ЯДРО — слова, которые в настоящем пароле practically не встречаются. Отбор строгий: `here` и
# `demo` из ядра УБРАНЫ (нашло независимое ревью) — это обычные английские слова, и с ними молчали
# правдоподобные НАСТОЯЩИЕ пароли `MyPasswordIsHere123`, `MyDemoPass2024`, `DemoApp2024`. Они
# остались наполнителем: сами по себе значение уже не прощают, но `your_password_here` прощается
# по-прежнему — там есть `your`.
_ЯДРО = ("changeme", "placeholder", "example", "sample", "dummy", "fake", "your",
         "todo", "replace", "insert")
# НАПОЛНИТЕЛЬ — нейтральные слова, которыми заглушки обрастают. Список НЕ обязан быть полным:
# незнакомое слово оставляет значение находкой, то есть пробел словаря стоит лишнего внимания, а не
# пропуска. Обратная сторона названа: `your.company.com` прощался раньше и стал находкой, пока
# `company` не попало сюда; сколько ещё таких слов — не замерено.
_НАПОЛНИТЕЛЬ = ("username", "password", "company", "service", "project", "endpoint", "account",
                "passwd", "apikey", "secret", "domain", "please", "string", "value", "token",
                "local", "login", "here", "demo", "goes", "site", "user", "name", "host", "pass",
                "data", "test", "key", "api", "app", "com", "net", "org", "url", "the", "pwd",
                "my", "me", "is")
# РАЗБОР СДЕЛАН КОДОМ, А НЕ РЕГУЛЯРКОЙ, И ЭТО НЕ ВКУСОВЩИНА.
#
# Первая версия проверяла «значение целиком из словарных слов» одним выражением вида
# `^(?:[-_. ]?(?:<40 альтернатив>|[0-9]{1,4}))+$`. Это КАТАСТРОФИЧЕСКИЙ ОТКАТ: цепочку из 34 цифр
# можно разбить на группы по 1–4 разными способами, и число путей растёт как 4^n. Замер на живом
# коде: значение `your` + 34 цифры НЕ ЗАВЕРШИЛО разбор за десять секунд. Ограничение длины входа
# от этого не спасало — значение короче потолка.
#
# Это был бы дефект дороже того, что чинится: сканер секретов стоит на блокирующем гейте и бежит
# на КАЖДОМ изменении, поэтому повисший разбор останавливает работу всей команды, а вызвать его
# может обычная строка с числом. Найдено собственным сторожем времени, а не в поле.
#
# Разбор ниже идёт СЛЕВА НАПРАВО и ничего не перебирает: на каждом шаге снимается разделитель,
# затем самое длинное подходящее слово словаря либо целая группа цифр. Время линейно по длине.
# Жадность без отката может не собрать разбор там, где перебор бы собрал, — и это безопасная
# сторона: значение останется находкой, то есть ошибка стоит лишнего внимания, а не пропуска.
_СЛОВАРЬ = tuple(sorted(_ЯДРО + _НАПОЛНИТЕЛЬ, key=len, reverse=True))
_ЯДРО_МН = frozenset(_ЯДРО)
# Потолок длины оставлен как здравый смысл, а не как защита от отката: заглушки длиннее — редкость,
# секреты длиннее — норма. Защита теперь в самом устройстве разбора.
ПОТОЛОК_ДЛИНЫ_ЗАГЛУШКИ = 80
_РАЗДЕЛИТЕЛИ = "-_. "


def _разбирается_на_слова_заглушки(значение: str) -> bool:
    """Значение ЦЕЛИКОМ раскладывается на словарные слова, цифры и разделители — и хотя бы одно
    слово из ядра. У настоящего секрета есть материал высокой энтропии, которого в словаре нет,
    поэтому разбор не сходится и значение остаётся находкой."""
    if not значение or len(значение) > ПОТОЛОК_ДЛИНЫ_ЗАГЛУШКИ:
        return False
    низ = значение.lower()
    место, конец, ядро_встретилось = 0, len(низ), False
    while место < конец:
        if низ[место] in _РАЗДЕЛИТЕЛИ:
            место += 1
            continue
        if низ[место].isdigit():
            while место < конец and низ[место].isdigit():
                место += 1
            continue
        for слово in _СЛОВАРЬ:                 # длинные первыми: `password` раньше `pass`
            if низ.startswith(слово, место):
                место += len(слово)
                ядро_встретилось = ядро_встретилось or слово in _ЯДРО_МН
                break
        else:
            return False                       # незнакомый материал -> это не заглушка
    return ядро_встретилось

_PLACEHOLDER = re.compile(
    # 1. СТРУКТУРНАЯ ПОДСТАНОВКА — это форма, а не значение: `${DB_PASSWORD}`, `<your-token>`.
    #    ГРАНИЦА ЧЕСТНОСТИ: `$` разрешён в пароле DSN, поэтому `Pr0d$ecret123` тоже молчит. Это
    #    осталось от прежнего кода и НЕ чинится здесь — названо, чтобы не выдавать за безопасное.
    r"(?i)(\$\{?[a-z_]+\}?|<[a-z_ -]+>|env\["
    # 3. ЗАМАЗКА: цепочка `x` ДО КОНЦА значения. Слева у замазки обычно оставляют опознаваемый
    #    префикс (`AIzaxxxxxxx…`, `sk_live_xxxxxxxx`), поэтому слева границы нет; справа конец
    #    значения обязателен — `xxxxxxA9zQ` и `Sxxxxxx_9Qz` не замазка, а материал с иксами внутри.
    r"|x{6,}$"
    # 4. ДОКУМЕНТНАЯ КОНВЕНЦИЯ AWS/RFC: `EXAMPLE` ВЕРХНИМ регистром и дальше до конца значения
    #    только заглавные — `AKIAIOSFODNN7EXAMPLE`, `…bPxRfiCYEXAMPLEKEY`. Это самый известный
    #    образец в документации, на нём сканер краснел ещё в замере 19.08.2026.
    #    ХВОСТ ОБЯЗАТЕЛЕН: без него одно заглавное слово внутри ЛЮБОГО формата отключало гейт —
    #    токены GitHub, OpenAI, Slack и npm с этим словом внутри не находились вовсе. (Образцы
    #    здесь НЕ приводятся дословно: строка формата токена в комментарии — это находка, и
    #    самоскан репозитория справедливо её поднимает. Они лежат в тестах, собранные из частей.)
    r"|(?-i:EXAMPLE[A-Z]*$)"
    r"|^pass(?:word)?$|^pwd$|^secret$|^token$"          # ровно слово, а не «passw0rd-от-базы»
    r"|^пароль$|^секрет$|^токен$"
    # Дальше — РЕГИСТРОЗАВИСИМЫЕ альтернативы: глобальный (?i) сделал бы их шире, чем обещают их же
    # комментарии. `^[А-ЯЁ]{4,}$` под (?i) ловил ЛЮБОЕ кириллическое слово от четырёх букв, включая
    # «МойПарольОтБазыПрод» — для русскоязычного продукта это настоящая форма пароля, а не заглушка.
    r"|(?-i:^[А-ЯЁ]{4,}$)"                             # кириллица: «ПАРОЛЬ», «СЕКРЕТ» — только КАПС
    # Тестовая заглушка ЦЕЛИКОМ из слов через дефис: `test-session-token`. Узко намеренно — цифры,
    # ВЕРХНИЙ РЕГИСТР и подчёркивания НЕ проходят, поэтому и `test_sk_live_A1b2…`, и
    # `TEST-SECRETPRODUCTIONVALUE` остаются флагами: префикс `test` не делает материал безобидным.
    # Регистр держится локальным флагом — под глобальным (?i) обещание было бы ложным.
    r"|(?-i:^(?:test|fake|dummy|sample)-[a-z-]+$))")

# ХОСТ НА ПЕТЛЕ — НЕ УТЕЧКА. Строка подключения к `localhost` не даёт доступа, который надо отзывать:
# пароль там либо от контейнера в CI, либо от машины разработчика. Вердикт судьи 24.09.2026 — 8
# находок из 17 ровно такие: дефолты сервис-контейнеров GitHub Actions, примеры локального запуска.
#
# ГРАНИЦА УЗКАЯ: правило применяется ТОЛЬКО к строке подключения. Любой другой формат (ключ, токен,
# JWT) остаётся находкой независимо от хоста — ключ остаётся ключом и на localhost.
#
# ХОСТ БЕРЁТСЯ У САМОЙ НАЙДЕННОЙ СТРОКИ ПОДКЛЮЧЕНИЯ, а не ищется по остатку текстовой строки. Иначе
# боевая утечка глохнет из-за постороннего `@localhost` где-то дальше в той же строке — например в
# комментарии рядом или во второй ячейке таблицы. Детектор берёт только ПЕРВОЕ совпадение на строке,
# поэтому такая ошибка означала бы пропуск настоящего секрета.
# ФОРМЫ ПЕТЛИ ПЕРЕЧИСЛЕНЫ, А ОКТЕТЫ ПРОВЕРЕНЫ (#1150). Прежде хост читался как `127` + три группы
# `\d{1,3}`, и это было асимметрично в обе стороны: `127.0.0.999` (несуществующий адрес) ПРОЩАЛСЯ,
# а живые записи петли — `127.1`, `[0:0:0:0:0:0:0:1]`, `[::ffff:127.0.0.1]` — оставались находками.
# Прощать невалидное опаснее: это единственная половина, где ошибка ведёт к пропуску.
# Вся сеть 127.0.0.0/8 — петля, поэтому годится любое число октетов: `127.1` и `127.0.0.1` равны.
# Ведущие нули разрешены: `127.000.000.001` — та же петля, и большинство резолверов её принимает.
_ОКТЕТ = r"(?:25[0-5]|2[0-4]\d|[01]?\d?\d)"
# Короткая запись — часть договора: `127.1` и `127.0.1` резолверы читают как 127.0.0.1.
_ПЕТЛЯ_V4 = r"127(?:\." + _ОКТЕТ + r"){1,3}"
# А ВОТ В IPv4-MAPPED ФОРМЕ СОКРАЩЕНИЙ НЕТ: `::ffff:` требует полного адреса. Прежде здесь стояла
# та же короткая форма, и прощался несуществующий `::ffff:127.1` — нашло независимое ревью. Прощать
# невалидное — единственная сторона этой асимметрии, ведущая к пропуску.
_ПЕТЛЯ_V4_ПОЛНАЯ = r"127(?:\." + _ОКТЕТ + r"){3}"
_ПЕТЛЯ_V6 = r"(?:::1|0{1,4}(?::0{1,4}){6}:0{0,3}1|::ffff:" + _ПЕТЛЯ_V4_ПОЛНАЯ + r")"
_LOOPBACK_HOST_AT_START = re.compile(
    r"^(?:localhost|" + _ПЕТЛЯ_V4 + r"|\[" + _ПЕТЛЯ_V6 + r"\]|" + _ПЕТЛЯ_V6 + r")"
    r"(?::\d+)?(?:[/?#\s\"']|$)", re.I)


def looks_like_placeholder(value: str) -> bool:
    """Значение — заглушка, а не секрет.

    Две проверки, а не одна: узнаваемые ФОРМЫ ловит выражение, а «значение целиком собрано из
    словарных слов» — разбор кодом (см. объяснение у `_разбирается_на_слова_заглушки`: тем же
    выражением это давало катастрофический откат)."""
    return bool(_PLACEHOLDER.search(value)) or _разбирается_на_слова_заглушки(value)


def is_loopback_dsn(host_and_rest: str) -> bool:
    """Хост НАЙДЕННОЙ строки подключения ведёт на свою машину.

    На вход идёт текст сразу после `@` совпавшего DSN: проверка привязана к началу, чтобы
    посторонний `@localhost` дальше по строке не гасил боевую находку.
    """
    return bool(_LOOPBACK_HOST_AT_START.match(host_and_rest))


# Материал ключа после заголовка PEM: base64-тело. Его отсутствие означает, что назван ФОРМАТ, а не
# выдан ключ — так заголовок и стоит в CHANGELOG, в манифесте и в отчёте аудита.
_PEM_BODY = re.compile(r"[A-Za-z0-9+/]{20,}")

# Сколько строк после заголовка считать телом ключа. Настоящий PEM начинает тело сразу; больший
# запас начал бы цеплять соседний текст.
PEM_LOOKAHEAD = 2


def pem_header_has_body(tail_of_line: str, next_lines: list) -> bool:
    """За заголовком PEM идут байты ключа — значит это ключ, а не упоминание формата.

    ТЕЛО ИЩЕТСЯ И НА СЛЕДУЮЩИХ СТРОКАХ, а не только в хвосте текущей: в настоящем PEM-файле
    заголовок стоит отдельной строкой, и проверка только своей строки пропустила бы ровно тот
    случай, ради которого правило существует.
    """
    return any(_PEM_BODY.search(t) for t in [tail_of_line, *next_lines])
