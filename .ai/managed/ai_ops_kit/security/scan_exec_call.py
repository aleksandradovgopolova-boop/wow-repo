"""Запуск команды: где он поверхность внедрения, а где безопасен по конструкции.

Сателлит `security_scan` (фасад импортирует отсюда `child_process_imported` и `surface_lines`).

ЧТО ПРАВИЛО ГАРАНТИРУЕТ — И ЧЕГО НЕ ГАРАНТИРУЕТ. Флаг снимается, когда в самой строке вызова видно,
что ИМЯ БИНАРЯ (`argv[0]`) записано литералом и оболочка не участвует: подставить ДРУГУЮ КОМАНДУ
туда нельзя. Это и есть внедрение команды — класс, ради которого правило существует.

Внедрение АРГУМЕНТОВ этим не покрывается и никогда не покрывалось: `execFileSync("git", args)` с
пользовательским `args` остаётся опасным (`git -c core.sshCommand=…`), и сканер этого не видит.
Формулировка «исполнится ровно то, что написано в файле» была бы НЕВЕРНОЙ — зафиксировано только
имя бинаря. Независимое ревью 25.09.2026 поймало это преувеличение в первой версии; оно исправлено
здесь и в changelog, а не сглажено. Частично класс всё же ловится: если среди аргументов ВИДЕН флаг,
которым бинарю передают код или команду (`-c`, `-e`, `--eval`, `-exec`, `--to-command`), вызов
остаётся поверхностью независимо от имени бинаря.

ПОЧЕМУ НЕ ПОМЕТИТЬ КАТАЛОГ `scripts/` ОБВЯЗКОЙ. Так было бы дешевле и так делать ЗАПРЕЩЕНО
(записано в `planning/plan.yaml` решением владельца): в `scripts/` живёт и эксплуатация — бэкап
базы, деплой, — а отказ от этого признака был осознанным в #1146. Это была бы подгонка замера под
планку. Точность правила работает и в боевом коде, а не только в каталоге с известным именем.

ЧТО ОСТАЁТСЯ ФЛАГОМ:
  * `exec`/`execSync` — ВСЕГДА через оболочку;
  * имя бинаря не литерал (переменная, шаблон с подстановкой, выражение);
  * литерал называет ОБОЛОЧКУ (`sh`, `bash`, `cmd`…) — в любом регистре и по любому пути;
  * среди аргументов виден флаг передачи кода/команды;
  * в опциях есть `shell` в любой форме, кроме доказанно ложной, — или россыпь `...opts`,
    внутри которой `shell` может оказаться.

Своей точки входа у сателлита нет осознанно: он обслуживает сканер, а не запускается сам.
"""
from __future__ import annotations

import re

CHILD_PROCESS_IMPORT = re.compile(
    r"""(?:require\s*\(\s*['"](?:node:)?child_process['"]|"""
    r"""from\s+['"](?:node:)?child_process['"]|"""
    r"""import\s+[^\n;]*['"](?:node:)?child_process['"])""")

# `spawn`/`fork` добавлены по разбору 24.09 (#1146): в ЕДИНСТВЕННОМ боевом месте исполнения команд
# на реальном продукте правило знало только `exec*` — и сканер называл строку `import`, а не строку
# вызова. Правило, существующее ради АДРЕСА, на боевом адресе адреса не давало.
_ВЫЗОВ = re.compile(r"\b(exec|execSync|execFile|execFileSync|spawn|spawnSync|fork)\s*\(")

# Семейство, которое ВСЕГДА идёт через оболочку: первый аргумент — целая командная строка.
_ЧЕРЕЗ_ОБОЛОЧКУ = frozenset({"exec", "execSync"})

# R-40, ВТОРОЙ ЗАХОД (#1112). `\b` в `_ВЫЗОВ` стоит между точкой и `e`, поэтому правило матчит и
# `.exec(` РЕГУЛЯРНОГО ВЫРАЖЕНИЯ. Чинится ПОЛУЧАТЕЛЕМ, а не сужением правила: `.exec(` с неизвестным
# получателем по-прежнему флагается — получатель может оказаться обёрткой над child_process.
#
# ПОЧЕМУ `/` ПЕРЕД `.exec(` ОДНОЗНАЧЕН: в JavaScript косая черта вплотную перед `.exec(` может быть
# только концом литерала регулярного выражения — деление `.exec(` за собой не ведёт.
# СНИМАЕТСЯ ТОЛЬКО `.exec(`, А НЕ ВЕСЬ ПОЛУЧАТЕЛЬ. Прежде выражение вырезалось целиком, и вместе с
# ним исчезал НАСТОЯЩИЙ вызов, стоявший внутри: `new RegExp(esc(spawn(bin, argv))).exec(line)`
# переставал быть поверхностью (нашло независимое ревью, десятый круг; носитель — минифицированный
# файл в одну строку). Теперь получатель остаётся на месте, а `.exec(` заменяется обычной скобкой:
# метод регулярки больше не читается как команда, а всё, что внутри, по-прежнему разбирается.
_ПОЛУЧАТЕЛЬ_РЕГУЛЯРКА = re.compile(r"((?:/|\bnew\s+RegExp\s*\([^\n]*?\)))\s*\.\s*exec\s*\(")
_ИМЯ_РЕГУЛЯРКИ = re.compile(
    r"""(?:const|let|var)\s+([A-Za-z_$][\w$]*)\s*=\s*(?:/|new\s+RegExp\s*\()""")

# Оболочки: литеральное имя здесь НЕ делает запуск безопасным — оболочка и есть способ внедрения.
# Сравнение регистронезависимое: на macOS и Windows файловая система тоже не различает регистр.
_ОБОЛОЧКИ = frozenset({"sh", "bash", "dash", "zsh", "ksh", "csh", "tcsh", "fish",
                       "cmd", "cmd.exe", "powershell", "powershell.exe", "pwsh",
                       "env", "xargs", "nohup", "timeout", "sudo", "su", "ssh"})
# Интерпретаторы: им короткие флаги можно СКЛЕИВАТЬ (`python3 -Sc`), поэтому для них правило шире.
_ИНТЕРПРЕТАТОРЫ = frozenset({"node", "nodejs", "deno", "bun", "python", "python2", "python3",
                             "ruby", "perl", "php", "osascript", "rscript", "lua"})

# ФЛАГИ ПЕРЕДАЧИ КОДА ИЛИ КОМАНДЫ. Форма `--eval=code` и склейка коротких флагов (`-Sc`) — рабочие
# формы, а не экзотика: обе проверены запуском. Хвост требует КОНЦА ТОКЕНА или `=`, поэтому
# `ffmpeg -c:v libx264` не матчится: там после `-c` идёт двоеточие, то есть флаг другой.
_КОНЕЦ_ТОКЕНА = r"(?=[=\s\"'`,\]\)]|$)"
_ФЛАГ_КОДА = re.compile(
    r"(?<![\w-])(?:--?(?:eval|print|command|to-command|exec)|-[ecp])" + _КОНЕЦ_ТОКЕНА)
_ФЛАГ_КОДА_СКЛЕЙКОЙ = re.compile(r"(?<![\w-])-[A-Za-z]*[ecp][A-Za-z]*" + _КОНЕЦ_ТОКЕНА)

# ОПЦИЯ `shell` ПРИЗНАЁТСЯ В ЛЮБОЙ ФОРМЕ, КРОМЕ ДОКАЗАННО ЛОЖНОЙ. Прежде проверялся литеральный
# `shell: true` — и молчали `shell: "/bin/sh"` (документированная опция Node, это ОБОЛОЧКА),
# `shell: !0`, `shell: opts.shell`, `{ ...opts }`. Нашло независимое ревью.
_SHELL_ЛОЖЬ = re.compile(r"""['"]?\bshell['"]?\s*:\s*(?:false|!1|0|undefined|null)\s*[,}]""")
_SHELL_КЛЮЧ = re.compile(r"""['"]?\bshell['"]?\s*:""")
# РОССЫПЬ СЧИТАЕТСЯ ТОЛЬКО В САМОМ ОБЪЕКТЕ ОПЦИЙ, а не где угодно в вызове. Два соседних случая на
# реальном продукте показали, почему нужна именно глубина:
#   * `[…, "run", ...tests]` — распаковка АРГУМЕНТОВ, опций там нет вовсе;
#   * `{ cwd: ROOT, env: { ...process.env } }` — распаковка ОКРУЖЕНИЯ, вложенная на уровень глубже;
#     `shell` в неё попасть не может.
# Опасна россыпь на ПЕРВОМ уровне фигурных скобок (`{ ...opts }`): туда `shell` приходит целиком.

# Сколько символов после открывающей скобки считать вызовом. Настоящий вызов укладывается с
# запасом; ограничение нужно, чтобы незакрытая скобка не утащила разбор через весь файл.
_ОКНО = 400


def without_regexp_exec(line: str, regexp_names: frozenset) -> str:
    """Убрать из строки вызовы `.exec(` у регулярных выражений — остальное трогать нельзя."""
    out = _ПОЛУЧАТЕЛЬ_РЕГУЛЯРКА.sub(r"\1(", line)
    for name in regexp_names:
        out = re.sub(r"\b(" + re.escape(name) + r")\s*\.\s*exec\s*\(", r"\1(", out)
    return out


def child_process_imported(text: str) -> bool:
    """Файл подключает `child_process` — только тогда `exec`-вызовы в нём считаем командами."""
    return bool(CHILD_PROCESS_IMPORT.search(text))


def _границы_вызова(скелет: str, начало: int) -> tuple:
    """-> (смещение закрывающей скобки или предела, закрылся ли вызов внутри окна).

    Скобки считаются по СКЕЛЕТУ — скобка внутри строкового литерала не должна сбивать счёт.
    ВТОРОЙ ОТВЕТ НУЖЕН, ЧТОБЫ ОКНО ОГРАНИЧИВАЛО, А НЕ ГАСИЛО: вызов длиннее окна прочитан не
    целиком, значит про его опции ничего не известно — и «ничего не известно» здесь означает
    поверхность, а не безопасность (нашло независимое ревью).
    """
    глубина, предел = 0, min(len(скелет), начало + _ОКНО)
    for i in range(начало, предел):
        if скелет[i] == "(":
            глубина += 1
        elif скелет[i] == ")":
            глубина -= 1
            if глубина == 0:
                return i, True
    return предел, False


def _первый_аргумент(окно: str) -> tuple:
    """-> (вид, значение). Вид: `литерал`, `execPath` или `неизвестно`.

    Литералом считается ТОЛЬКО строка в кавычках без подстановки: шаблон с `${...}` — это уже
    значение, собранное из данных, и его содержимое неизвестно на момент чтения кода.
    """
    текст = окно.lstrip()
    if not текст:
        return ("неизвестно", "")
    if текст.startswith("process.execPath"):
        return ("execPath", "node")
    кавычка = текст[0]
    if кавычка not in "\"'`":
        return ("неизвестно", "")
    i, значение = 1, []
    while i < len(текст):
        сим = текст[i]
        if сим == "\\":
            i += 2
            continue
        if сим == кавычка:
            собрано = "".join(значение)
            if кавычка == "`" and "${" in собрано:
                return ("неизвестно", "")       # шаблон с подстановкой — не литерал
            return ("литерал", собрано)
        значение.append(сим)
        i += 1
    return ("неизвестно", "")                    # кавычка не закрылась в окне


def _имя_бинаря(значение: str) -> str:
    """Последний сегмент пути без каталогов и без регистра: `/bin/BASH` -> `bash`."""
    return значение.replace("\\", "/").rsplit("/", 1)[-1].strip().lower()


def _россыпь_в_опциях(скелет: str) -> bool:
    """`...` на ПЕРВОМ уровне фигурных скобок вызова — объект опций собран из чужого значения."""
    глубина = 0
    for i, сим in enumerate(скелет):
        if сим == "{":
            глубина += 1
        elif сим == "}":
            глубина -= 1
        elif глубина == 1 and скелет.startswith("...", i):
            return True
    return False


def launch_is_a_surface(функция: str, окно: str, окно_скелет: str = None) -> bool:
    """Этот запуск команды — поверхность внедрения?

    `окно` — текст аргументов как он написан (флаги живут ВНУТРИ строковых литералов, поэтому их
    ищем здесь). `окно_скелет` — он же с погашенным содержимым строк, по нему ищутся опции: слово
    `shell` внутри строки опцией не является. По умолчанию скелет считается сам.

    Ответ «нет» даётся ТОЛЬКО когда безопасность видна по конструкции в самом вызове.
    """
    if функция in _ЧЕРЕЗ_ОБОЛОЧКУ:
        return True                              # оболочка участвует всегда
    # Без скелета опции ищутся по СЫРОМУ окну: это ошибка в сторону лишнего флага (слово `shell`
    # внутри строкового аргумента), а не пропуска. Разбор строк живёт в `scan_prose` — одна копия
    # эвристики на весь сканер, и сюда она приходит готовым скелетом.
    скелет = окно if окно_скелет is None else окно_скелет
    if _россыпь_в_опциях(скелет):
        return True                              # `{ ...opts }` — внутри может оказаться `shell`
    # КЛЮЧ ИЩЕТСЯ ПО СЫРОМУ ОКНУ, а не по скелету: скелет гасит содержимое кавычек, и
    # `{ "shell": true }` переставал опознаваться — префикс `['"]?` в выражении был мёртвым
    # (нашло независимое ревью). Цена: слово `shell:` внутри строкового аргумента даст лишний флаг.
    # Это безопасная сторона, и она дешевле пропущенной оболочки.
    if _SHELL_КЛЮЧ.search(окно) and not _SHELL_ЛОЖЬ.search(окно):
        return True                              # `shell` в любой форме, кроме доказанно ложной
    вид, значение = _первый_аргумент(окно)
    if вид == "неизвестно":
        return True                              # имя бинаря неизвестно на момент чтения кода
    бинарь = _имя_бинаря(значение)
    if бинарь in _ОБОЛОЧКИ:
        return True
    if _ФЛАГ_КОДА.search(окно):
        return True                              # бинарю передают код или команду — видно прямо тут
    if (бинарь in _ИНТЕРПРЕТАТОРЫ or вид == "execPath") and _ФЛАГ_КОДА_СКЛЕЙКОЙ.search(окно):
        return True                              # интерпретаторам короткие флаги можно склеивать
    return False


# ИМЕНА, ПОД КОТОРЫМИ `child_process` ВОШЁЛ В ФАЙЛ. Нужны, чтобы утверждение «вызовы разобраны»
# стало ПРОВЕРЯЕМЫМ. Прежде оно значило «разобрано всё, что нашла регулярка `_ВЫЗОВ`», а не «всё,
# что есть в файле», — и рядом с безопасным литеральным запуском молчали `exec as run`,
# `const { exec: sh }`, `promisify(exec)`, `cp["exec"](…)`. Каждая из этих форм — идиома, а не
# экзотика; последняя вообще та, которой обосновано гашение строк. Нашло независимое ревью,
# десятый круг.
_ИМПОРТ_ИМЕНА = re.compile(
    r"""import\s+(?:\*\s+as\s+(?P<ns1>[A-Za-z_$][\w$]*)|(?P<def>[A-Za-z_$][\w$]*)\s*,?\s*)?"""
    r"""(?:\{(?P<named>[^}]*)\})?\s*from\s*['"](?:node:)?child_process['"]"""
    r"""|(?:const|let|var)\s*(?:\{(?P<named2>[^}]*)\}|(?P<ns2>[A-Za-z_$][\w$]*))\s*="""
    r"""\s*require\s*\(\s*['"](?:node:)?child_process['"]""")
_ПСЕВДОНИМ = re.compile(r"([A-Za-z_$][\w$]*)\s*(?::|\bas\b)\s*([A-Za-z_$][\w$]*)|([A-Za-z_$][\w$]*)")


def bound_names(код: str) -> frozenset:
    """Имена, которыми в этом файле пользуются `child_process`: и пространство, и отдельные функции."""
    имена = set()
    for m in _ИМПОРТ_ИМЕНА.finditer(код):
        for группа in ("ns1", "def", "ns2"):
            if m.group(группа):
                имена.add(m.group(группа))
        for группа in ("named", "named2"):
            кусок = m.group(группа)
            if not кусок:
                continue
            for часть in кусок.split(","):
                # ТИПОВОЙ ИМПОРТ НЕ СОЗДАЁТ ИМЕНИ ВО ВРЕМЯ РАБОТЫ. `import { spawn, type
                # ChildProcess }` — вторая часть существует только для проверки типов. Без этого
                # отсева именем считалось слово `type`, и любое поле `"type":` в файле выглядело
                # неразобранным обращением: два файла реального продукта получили лишний флаг.
                часть = часть.strip()
                if часть.startswith("type ") or часть == "type":
                    continue
                п = _ПСЕВДОНИМ.search(часть)
                if п:
                    имена.add(п.group(2) or п.group(3))
    return frozenset(и for и in имена if и)


def _все_обращения_разобраны(код: str, скелет: str, разобранные: set) -> bool:
    """Каждое упоминание имени из `child_process` стоит на РАЗОБРАННОМ вызове?

    `разобранные` — смещения имён, которые нашла `_ВЫЗОВ`. Обращение засчитывается, если оно стоит
    ровно там, либо это пространство имён перед разобранным вызовом (`cp.execFileSync(…)`), либо
    это сама строка импорта. Всё прочее — форма, которую разбор не понял, и тогда снимать флаг со
    строки импорта нельзя: молчание там означало бы «не проверено», выданное за «чисто».
    """
    строки_импорта = {код.count("\n", 0, m.start()) for m in _ИМПОРТ_ИМЕНА.finditer(код)}
    for имя in bound_names(код):
        for m in re.finditer(r"\b" + re.escape(имя) + r"\b", скелет):
            if m.start() in разобранные or код.count("\n", 0, m.start()) in строки_импорта:
                continue
            # ОБРАЩЕНИЕ ПОСЛЕ ТОЧКИ — ЧЛЕН ЧУЖОГО ОБЪЕКТА, А НЕ ССЫЛКА НА ИМПОРТ: `RE.exec(s)` —
            # метод регулярного выражения. Если точка стоит после ИМЕНИ ПРОСТРАНСТВА (`cp.exec(…)`),
            # вызов узнаётся правилом и попадает в разобранные сам.
            if скелет[:m.start()].rstrip().endswith("."):
                continue
            хвост = скелет[m.end():m.end() + 40].lstrip()
            if хвост.startswith(".") and _ВЫЗОВ.match(хвост[1:].lstrip()):
                continue                       # `cp.execFileSync(` — вызов разобран на члене
            return False
    return True


def _разобрать(код: str, скелет: str, имена_регулярок: frozenset) -> tuple:
    """-> (строки всех найденных вызовов, строки вызовов-поверхностей) для ОДНОГО прочтения."""
    строки, строки_скелета = код.splitlines(), скелет.splitlines()
    # СМЕЩЕНИЯ СЧИТАЮТСЯ ПО СТРОКАМ С КОНЦАМИ. `splitlines()` отбрасывает перенос, и прибавка «+1»
    # закладывает ОДНОБАЙТОВЫЙ разделитель — на файле с виндовым переносом (`\r\n`) смещение
    # недосчитывало байт на каждой строке, дрейф копился, и окно вызова читалось со сдвигом: разбор
    # видел чужие байты и объявлял настоящую поверхность безопасной. Боевой адрес ИСЧЕЗАЛ из отчёта,
    # оставляя судью на заведомо чистой строке выше. На прежнем коде этого не было — регресс внесён
    # переходом на окна, нашло независимое ревью (девятый круг). `keepends=True` считает фактическую
    # длину, какой бы перенос ни стоял, включая юникодные разделители строк.
    смещения, позиция = [], 0
    for строка_с_концом in код.splitlines(keepends=True):
        смещения.append(позиция)
        позиция += len(строка_с_концом)
    вызовы, поверхности, разобранные = set(), set(), set()
    for номер, (строка, строка_скелета) in enumerate(zip(строки, строки_скелета), 1):
        очищенная = without_regexp_exec(строка_скелета, имена_регулярок)
        if not _ВЫЗОВ.search(очищенная):
            continue
        for m in _ВЫЗОВ.finditer(строка_скелета):
            if m.group(1) == "exec" and not _ВЫЗОВ.search(
                    without_regexp_exec(строка_скелета[:m.end()], имена_регулярок)):
                continue
            вызовы.add((номер, m.start()))
            разобранные.add(смещения[номер - 1] + m.start())
            старт = смещения[номер - 1] + m.end() - 1
            конец, закрылся = _границы_вызова(скелет, старт)
            if not закрылся or launch_is_a_surface(
                    m.group(1), код[старт + 1:конец], скелет[старт + 1:конец]):
                поверхности.add(номер)
                break                            # на строке довольно одного адреса
    return вызовы, поверхности, разобранные


def surface_lines(код: str, прочтения) -> tuple:
    """-> (можно ли снимать флаг с импорта, номера строк-поверхностей).

    ДВА ПРОЧТЕНИЯ, А НЕ ОДНО, И ЭТО ОТВЕТ НА ШЕСТОЙ КРУГ РЕВЬЮ. Обратная кавычка в JavaScript
    открывает шаблонную строку, а в тексте разметки JSX это обычный символ. Отличить их без разбора
    языка нельзя, и ПЯТЬ попыток угадать позиционной эвристикой дали пять дверей подряд: сначала
    код между бродячими кавычками исчезал из разбора, потом — наоборот — содержимое настоящих
    шаблонов читалось как код.

    Поэтому угадывание убрано совсем. Файл читается ОБА раза, и:
      * АДРЕСА берутся ОБЪЕДИНЕНИЕМ — ни одна поверхность не теряется из-за неудачного прочтения;
      * флаг со строки `import` снимается, ТОЛЬКО когда оба прочтения нашли одни и те же вызовы и
        оба разобрались до конца. Разошлись — значит текст неоднозначен, и снимать флаг нельзя:
        именно в этом зазоре и жили все шесть дверей.

    Цена названа: файл, где внутри шаблонной строки лежит текст, похожий на вызов, останется с
    флагом на импорте. Это лишнее внимание, а не пропуск.

    На вход идёт текст БЕЗ КОММЕНТАРИЕВ (#1146): закомментированный вызов не исполняется, а раз
    найденный вызов снимает флаг со строки импорта, такой «вызов» уводил бы судью с настоящей
    строки — и этим можно было бы управлять снаружи, дописав комментарий.

    РАЗБИРАЮТСЯ ВСЕ ВЫЗОВЫ НА СТРОКЕ, а не первый: безопасный слева гасил опасный справа.
    """
    имена_регулярок = frozenset(_ИМЯ_РЕГУЛЯРКИ.findall(код))
    общие, поверхности, согласны = None, set(), True
    for скелет, разбор_состоялся in прочтения:
        вызовы, найдено, разобранные = _разобрать(код, скелет, имена_регулярок)
        поверхности |= найдено
        if not разбор_состоялся or not _все_обращения_разобраны(код, скелет, разобранные):
            согласны = False
        if общие is None:
            общие = вызовы
        elif общие != вызовы:
            согласны = False
    return bool(общие) and согласны, sorted(поверхности)



def launch_findings(text: str, path: str, гасить_комментарии, гасить_строки) -> tuple:
    """-> как у `surface_lines`, для файла с `child_process`. Разборщики из `scan_prose` приходят
    параметрами: импорт соседа сломал бы загрузку по пути (запуск скриптом).

    ГРАНИЦЫ (#1153). Строки гасятся ТОЛЬКО ДЛЯ ПОИСКА имени вызова (`'call execSync(cmd)'` вызовом
    не считается), аргументы читаются со строками — иначе не видна команда, склеенная из
    строкового литерала и переменной прямо в аргументе `exec`. Файл с
    неизвестным суффиксом (`Jenkinsfile`) читается по правилам JS, но язык ВЫБРАН, а не узнан:
    флаг импорта у него не снимается (кроме `#!` для node). Цена — лишнее внимание, не пропуск.
    """
    код, комментарии_разобраны = гасить_комментарии(text, path, неизвестный_как=".js")
    прочтения = tuple((скелет, ок and комментарии_разобраны)
                      for скелет, ок in (гасить_строки(код), гасить_строки(код, шаблоны=False)))
    return surface_lines(код, прочтения)
