"""Поставленная зависимость: что из найденного ПРИЕХАЛО с обновлением кита, а что было и раньше.

Сателлит `security_scan` (фасад импортирует отсюда `VERSION_FILE` и `mark_arrivals`; сам признак
«это установленная копия кита» живёт в `scan_prose.area_of` вместе с остальными областями).

ЗАЧЕМ ОТДЕЛЬНЫЙ РАЗДЕЛ, А НЕ ПРОЩЕНИЕ. Флаги на `.ai/managed/` — про код, который дочка не писала
и починить в своём PR не может. Но «перестать смотреть» — не починка: тогда кит молча привозил бы
в чужой репозиторий injection-поверхность, за которую отвечает сам. Поэтому адреса видны все до
одного, отдельным разделом, с другим адресатом и БЕЗ участия в вердикте гейта продукта.

ПОЧЕМУ СРАВНЕНИЕ ПО ТЕКСТУ СТРОКИ, А НЕ ПО НОМЕРУ. Между версиями кита номера строк съезжают от
любой правки выше по файлу — сравнение по номеру объявило бы «новым» каждый сдвинувшийся адрес и
утопило бы единственный настоящий. Опознание — пара «правило + текст строки»; счётчиком, а не
множеством, чтобы второй такой же вызов в том же файле считался новым адресом, а не дублем.

Своей точки входа у сателлита нет осознанно: он обслуживает сканер, а не запускается сам.
"""
from __future__ import annotations

from collections import Counter

# Версия установленного кита — ею подписан раздел: «эти адреса приехали с обновлением 4.5 -> 4.6».
# Файл кладёт сам установщик, и он же его перезаписывает при обновлении.
VERSION_FILE = ".ai/managed/VERSION"


def _fingerprint(flag: dict, lines: list) -> tuple:
    """Опознание адреса: правило + текст его строки. Переживает сдвиг строк между версиями."""
    i = flag.get("line", 0) - 1
    return (flag.get("id"), lines[i].strip() if 0 <= i < len(lines) else "")


def mark_arrivals(flags, text_after: str, before_flags, text_before: str) -> list:
    """Проставить `arrived` каждому флагу: True — адрес приехал с ЭТОЙ версией кита, False — был.

    Порядок флагов сохраняется. `arrived` — ЯРЛЫК, а не фильтр: ни один адрес не исчезает, раздел
    печатает все, просто приехавшие названы отдельно.

    ГРАНИЦА ЧЕСТНОСТИ: если прежнего текста файла нет (файл появился с этим обновлением, ЛИБО
    git не отдал содержимое), все адреса в нём считаются приехавшими. Ошибка здесь уводит в
    сторону лишнего внимания, а не пропуска, — и это единственная безопасная сторона для раздела,
    который ничего не блокирует.
    """
    # СЧЁТЧИК, А НЕ МНОЖЕСТВО: если в прежней версии такой вызов был ОДИН, а стало ДВА дословно
    # одинаковых, второй — новый адрес. Множество объявило бы его старым (сторож — тест
    # `test_a_second_identical_call_is_a_new_address`).
    было = Counter(_fingerprint(f, text_before.splitlines()) for f in before_flags)
    строки = text_after.splitlines()
    out = []
    for f in flags:
        fp = _fingerprint(f, строки)
        приехал = было[fp] <= 0
        if not приехал:
            было[fp] -= 1
        out.append({**f, "arrived": приехал})
    return out


def arrivals_note(version_before, version_after, arrived: int, total: int, compared: bool) -> str:
    """Подпись раздела: чей это код, с какой версией приехало и сколько адресов новых.

    `compared=False` — базы для сравнения не было, и «новых нет» тогда не факт, а НЕЗНАНИЕ. Кит
    различает их везде (тот же инвариант, что у `dependencies_compared`), и здесь обязан различать
    тоже: иначе прогон по всему дереву выдавал бы «всё это было и раньше» бесплатно."""
    чей = "адресат — сопровождающий кита, не эта команда; в вердикт гейта продукта не входит"
    # «ВЕРСИЯ НЕ МЕНЯЛАСЬ» — ТОЖЕ ВЫВОД ИЗ СРАВНЕНИЯ, и без базы его делать нельзя. Прежде эта
    # фраза печаталась рядом с «с прежней версией НЕ СРАВНИВАЛИСЬ» — одно предложение утверждало
    # и то, и другое (нашло независимое ревью).
    if not version_after:
        чем = "версия кита не прочиталась"
    elif not compared:
        чем = f"кит {version_after}"
    elif version_before and version_before != version_after:
        чем = f"обновление кита {version_before} -> {version_after}"
    elif version_before:
        чем = f"кит {version_after}, версия не менялась"
    else:
        чем = f"кит {version_after}, прежняя версия не записана"
    if not compared:
        сколько = (f"{total} адресов; с прежней версией НЕ СРАВНИВАЛИСЬ — база не задана "
                   f"(--base <ревизия>), какие из них приехали с обновлением, неизвестно")
    else:
        сколько = f"{total} адресов, из них приехало с этим обновлением {arrived}"
    return f"{чей}. {чем}; {сколько}"
