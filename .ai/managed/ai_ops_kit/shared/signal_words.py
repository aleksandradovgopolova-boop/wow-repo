#!/usr/bin/env python3
"""Разбор size/risk из ОБЫЧНЫХ СЛОВ — человеческий путь ответа на `--signals` (#864).

ПРОБЛЕМА (живой zero-touch прогон): когда тяжесть задачи не заявлена, кит просит владельца
ответить `--signals '{"size":"small","risk":"low"}'` — то есть написать JSON. Это техническое
действие ровно там, где человек мог бы просто сказать «небольшая, неопасная». JSON — рабочий,
внутренний формат кита; он не обязан быть единственным способом ответить.

Здесь — детерминированный, без модели, разбор фразы на русском или английском в {"size": ...,
"risk": ...}. Никакой магии: ищем в тексте известные слова и сопоставляем со значением. Часть
фразы, которую не удалось узнать, молча пропускается — вызывающий (`ai_ops_cli._build_signals`)
решает, считать ли результат достаточным ответом.

Порядок словарей важен: короткие/отрицательные формы («небольшая», «неопасная») проверяются
РАНЬШЕ более длинных положительных («большая», «рискованная»), потому что первые содержат вторые
как подстроку («не-большая», «не-опасная»). Проверка по порядку "small/low -> ... -> large/high"
не даёт «большая» откликнуться на «небольшая» раньше своей очереди.
"""
from __future__ import annotations

# Ключ — итоговое значение size/risk (то же, что ждёт spec_levels/atomic_planner). Значение —
# слова-триггеры на русском и английском, которые встречаются в свободной фразе владельца.
_SIZE_WORDS = {
    "small": ("небольшая", "небольшой", "небольшое", "маленькая", "маленький", "мелкая",
              "мелкий", "малая", "малый", "small", "тривиальная", "крошечная"),
    "medium": ("средняя", "средний", "среднее", "умеренная", "умеренный", "medium"),
    "large": ("большая", "большой", "большое", "крупная", "крупный", "large"),
    "xl": ("огромная", "огромный", "гигантская", "гигантский", "очень большая", "xl",
           "extra large", "экстремально большая"),
}

_RISK_WORDS = {
    "low": ("неопасная", "неопасный", "не рискованная", "не рискованный", "нерискованная",
            "нерискованный", "безопасная", "безопасный", "без риска", "низкий риск",
            "невысокий риск", "низкая", "low"),
    "medium": ("средний риск", "умеренный риск", "средняя рискованность", "medium"),
    "high": ("рискованная", "рискованный", "опасная", "опасный", "высокий риск", "high"),
    "critical": ("критическая", "критический", "критично", "критический риск", "critical"),
}

# Порядок обхода: короткие/отрицательные формы — раньше длинных положительных (см. модульный
# докстринг). Ключи словарей выше уже идут в этом порядке (small/low первыми), поэтому здесь
# просто фиксируем порядок итерации явным списком — не полагаемся молча на порядок вставки dict.
_SIZE_ORDER = ("small", "medium", "large", "xl")
_RISK_ORDER = ("low", "medium", "high", "critical")


def _first_match(norm_text: str, words_by_value: dict[str, tuple[str, ...]], order: tuple[str, ...]) -> str | None:
    for value in order:
        if any(word in norm_text for word in words_by_value[value]):
            return value
    return None


def parse_plain_signals(text: str) -> dict:
    """Разобрать свободную фразу о размере/риске задачи в {"size": ..., "risk": ...}.

    Понимает русские и английские слова (пример: «небольшая, неопасная» -> {"size": "small",
    "risk": "low"}). Распознаёт size и risk независимо — можно назвать только один из них.
    Часть, которую не удалось узнать, в результат не попадает (не гадаем).

    -> {} , если в тексте не нашлось ни одного известного слова.
    """
    norm = (text or "").strip().lower().replace("ё", "е")
    if not norm:
        return {}
    out = {}
    size = _first_match(norm, _SIZE_WORDS, _SIZE_ORDER)
    if size:
        out["size"] = size
    risk = _first_match(norm, _RISK_WORDS, _RISK_ORDER)
    if risk:
        out["risk"] = risk
    return out


def looks_like_plain_words(text: str) -> bool:
    """Эвристика «это не JSON, а обычная фраза» — используется ТОЛЬКО для сообщений/логов
    (что именно сработало), не для решения, парсить или нет: `_build_signals` сначала пробует
    JSON и падает на словах естественным путём через исключение."""
    t = (text or "").strip()
    return bool(t) and not t.startswith("{")
