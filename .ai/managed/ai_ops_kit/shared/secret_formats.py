"""Форматы секретов — ОДИН источник истины для детектора и для всех скрабов (#1097).

ПОЧЕМУ ОТДЕЛЬНЫЙ МОДУЛЬ, А НЕ КОПИИ. Список форматов нужен трём разным потребителям:
  * `security/security_scan.py`     — ДЕТЕКТИРУЕТ секрет в изменённых файлах (гейт no_secrets);
  * `engine/tool_broker._scrub_output` — ЗАТИРАЕТ секрет в выводе инструментов перед evidence;
  * `delivery/pr_open`              — ЗАТИРАЕТ секрет в теле PR и в git-stderr перед отправкой.
До #1097 канонический список жил в детекторе, а доставка держала СВОЮ копию четырёх правил с
комментарием «держать в синхроне». Синхрон держался вручную и разошёлся: после #1094 детектор
знал строку подключения с паролем, JWT, npm-токен и ключи LLM-провайдеров, а скраб тела PR — нет.
Кит сам пишет тела PR, то есть знал формат и всё равно печатал его наружу. Расхождение, которое
чинится правкой в двух файлах, рано или поздно расходится снова, поэтому список здесь один.

ПОЧЕМУ ИМЕННО `shared` И ПОЧЕМУ БЕЗ ЕДИНОГО ИМПОРТА ИЗ ПАКЕТА — два ограничения сразу:
  1. `security_scan.py` запускается КАК СКРИПТ (`python3 ai_ops_kit/security/security_scan.py`
     в CI) и не вправе импортировать пакет `ai_ops_kit` (sys.path[0] — каталог скрипта). Он
     грузит этот файл ПО ПУТИ от своего `__file__` — а грузить по пути можно только модуль,
     которому для работы не нужен пакет вокруг. Поэтому здесь нет ни одного импорта из
     `ai_ops_kit`, и появиться он не вправе: это сломает запуск сканера в CI.
  2. `delivery` не вправе импортировать `security` (гейт слоёв, ратчет layering). `shared` —
     фундамент, от него вправе зависеть любой слой, поэтому общий примитив встаёт сюда, и
     кольцо зависимостей остаётся DAG'ом.

ОБРАЗЦЫ СЕКРЕТОВ ЗДЕСЬ НЕ ПИШУТСЯ ДОСЛОВНО (решение v3.0.4): собственный материал детектора
секретов не прощается списком, поэтому дословный пример тут же нашёл бы сам сканер. Образцы
собираются из фрагментов в тестах (`tests/unit/test_security_scan.py`,
`tests/unit/test_secret_formats_single_source.py`).
"""
from __future__ import annotations

import re
from typing import Iterable

# Чем заменяется найденное значение. Маркер ОДИН на все каналы: по нему в отчёте видно, что текст
# не пропал, а был отредактирован. Скраб — это замена значения, а не отказ печатать текст.
REDACTION_MARKER = "«***REDACTED-SECRET***»"

# Известные форматы секретов: (идентификатор, шаблон). Порядок значим только для отчёта детектора.
# Пароль/значение вынесены в ГРУППУ там, где детектору нужно отсеять плейсхолдер по НАЙДЕННОМУ
# значению (`security_scan._PLACEHOLDER`), а не по всей строке.
SECRET_FORMATS: list[tuple[str, re.Pattern[str]]] = [
    ("aws_access_key_id", re.compile(r"\bAKIA[0-9A-Z]{16}\b")),
    ("private_key_block", re.compile(r"-----BEGIN (?:RSA |EC |OPENSSH |DSA |PGP )?PRIVATE KEY-----")),
    ("github_pat", re.compile(r"\bghp_[A-Za-z0-9]{36}\b")),
    ("slack_token", re.compile(r"\bxox[baprs]-[0-9A-Za-z-]{10,}\b")),
    ("google_api_key", re.compile(r"\bAIza[0-9A-Za-z_\-]{35}\b")),
    ("aws_secret_access_key", re.compile(r"(?i)aws_secret_access_key\s*[:=]\s*['\"]?[A-Za-z0-9/+]{40}\b")),
    ("generic_secret_assignment",
     re.compile(r"(?i)\b(?:api[_-]?key|secret|token|password|passwd|access[_-]?key)\b\s*[:=]\s*"
                r"['\"]([A-Za-z0-9/+_\-]{16,})['\"]")),
    # ── #1094: форматы профиля «Node/TS + БД». До них ни один из семи шаблонов выше не ловил
    # самый вероятный утёк такого продукта — строку подключения с паролем внутри.
    #
    # Пароль вынесен в ГРУППУ намеренно: отсев плейсхолдеров (`_PLACEHOLDER`) работает по
    # НАЙДЕННОМУ значению, и поэтому строка, где на месте пароля стоит `${…}` или `changeme`,
    # молчит, а строка с настоящим паролем — нет.
    #
    # Пароль короче трёх символов не считаем утечкой: в собственных фикстурах кита стоит
    # односимвольный пароль в URL, и флаг на нём был бы шумом, а не находкой (замер на дереве
    # кита 22.09.2026).
    ("db_connection_string_password",
     re.compile(r"\b(?:postgres(?:ql)?|mysql|mariadb|mongodb(?:\+srv)?|redis(?:s)?|amqps?|mssql)"
                r"://[^\s:/@'\"<>]+:([^\s:/@'\"<>]{3,})@")),
    ("npm_token", re.compile(r"\bnpm_[A-Za-z0-9]{36}\b")),
    # JWT известен ложными срабатываниями, поэтому привязан строго: заголовок начинается с `eyJ`
    # (это base64url от `{"`), три сегмента base64url реалистичной длины. `a.b.c` и любой путь
    # с точками сюда не попадают.
    ("jwt_token",
     re.compile(r"\beyJ[A-Za-z0-9_-]{8,}\.[A-Za-z0-9_-]{16,}\.[A-Za-z0-9_-]{16,}(?![A-Za-z0-9_-])")),
    # Ключи LLM-провайдеров. Anthropic: `sk-ant-…` (реальный ~100 символов). OpenAI-подобные:
    # `sk-`/`sk-proj-` + длинный АЛФАВИТНО-ЦИФРОВОЙ хвост без дефисов — дефис в хвосте разрешать
    # нельзя, иначе шаблон начинает ловить длинные kebab-case имена вида `sk-loading-spinner-…`.
    ("anthropic_api_key", re.compile(r"\bsk-ant-[A-Za-z0-9_-]{32,}")),
    ("openai_api_key", re.compile(r"\bsk-(?:proj-)?[A-Za-z0-9]{32,}\b")),
]


def scrub(text: str | None, extra: Iterable[tuple[re.Pattern[str], str]] = ()) -> str | None:
    """Затереть в тексте все известные форматы секретов. -> текст с маркерами вместо значений.

    ЭТО СКРАБ, А НЕ ДЕТЕКТОР: здесь нет отсева плейсхолдеров. Детектору важно не поднимать флаг на
    `${DB_PASSWORD}`; скрабу затереть плейсхолдер не вредно, а вот пропустить настоящее значение,
    потому что оно «похоже на пример», — вредно. Поэтому правила применяются как есть.

    `extra` — дополнительные правила (шаблон, замена) КАНАЛА-потребителя: форматы, которых в
    каноническом списке нет, потому что детектору они не нужны (например креды, встроенные в
    `https://`-URL удалённого репозитория). Применяются ПОСЛЕ канонических.

    Исключения НЕ гасятся: вызывающий обязан решить, что делать со сбоем скраба. Оба сегодняшних
    потребителя решают одинаково — fail-closed, содержимое не показывается вовсе.
    """
    if not text:
        return text
    for _fid, pattern in SECRET_FORMATS:
        text = pattern.sub(REDACTION_MARKER, text)
    for pattern, replacement in extra:
        text = pattern.sub(replacement, text)
    return text
