#!/usr/bin/env python3
"""Продуктовый язык связи РИСК -> ЦЕРЕМОНИЯ (спутник presenter_formatters, направление
risk-based-ceremony).

Вынесено из `presenter_formatters.py`, чтобы фасад держался под потолком размера модуля. Здесь —
единственная чистая функция `risk_ceremony_line`: она переводит уже посчитанную детерминированно
связь «уровень + причина» (gates.spec_levels.classify) на язык человека. Жаргон (task_type=…,
L0/L3, size/risk/эскалация) сюда не течёт — он остаётся в технических деталях; человек видит смысл.
Слой `ui` НЕ импортирует `gates`: `level_reason` приходит СЮДА как данные (список строк reason),
а не через импорт вверх.
"""
from __future__ import annotations

# Сколько процесса — ПРОДУКТОВЫМИ словами (НЕ имя уровня L0/L3: это жаргон, остаётся в техдеталях).
# Ключ — level_name из gates.spec_levels (данные, не импорт).
_CEREMONY_AMOUNT = {
    "L0 QUICK": "процесса минимум",
    "L1 ENGINEERING": "процесса немного",
    "L2 PRODUCT": "процесса среднего объёма",
    "L3 CRITICAL": "процесса по максимуму",
}


def risk_ceremony_line(level_name, level_reason=None, provisional=False) -> str:
    """Одна человеческая строка: ОБЪЁМ процесса подобран по РИСКУ изменения, а не по «заполни всё».

    Исход `ceremony_scales_with_risk_not_completeness`: связь риск->церемония уже посчитана
    детерминированно в gates.spec_levels.classify (уровень + reason). Здесь она ПЕРЕВОДИТСЯ на
    продуктовый язык — сколько процесса и ПОЧЕМУ именно столько. `level_reason` — список строк
    classify['reason']; читаем его как ДАННЫЕ (маркеры эскалации), не импортируя слой гейтов.
    """
    reason = " ".join(level_reason or [])
    amount = _CEREMONY_AMOUNT.get(level_name, "процесса ровно столько, сколько требует риск")
    if "secret_boundary=True" in reason:
        why = "изменение трогает границу секретов — риск высокий"
    elif "irreversible=True" in reason:
        why = "изменение необратимо — риск высокий"
    elif "эскалация до L3" in reason:
        why = "риск изменения высокий (критичность, необратимость или секреты)"
    elif "измеримое пользовательское изменение" in reason:
        why = "изменение видит пользователь и его надо измерить"
    elif (level_name or "").startswith("L3"):
        # Базовый CRITICAL (task_type=CRITICAL / requested_level=3): уровень уже 3, маркера
        # «эскалация до L3» classify не добавляет (level < 3 не выполнено). Без этой ветки строка
        # падала в else и ЛГАЛА «мелкая и обратимая — риск низкий» на самой рискованной задаче.
        why = "изменение критическое или необратимое — риск максимальный"
    elif (level_name or "").startswith("L2"):
        why = "изменение продуктовое — его надо описать и измерить"
    elif (level_name or "").startswith("L1"):
        why = "инженерная задача умеренного масштаба"
    else:
        why = "задача мелкая и обратимая — риск низкий"
    line = (f"Объём процесса подобран под РИСК изменения, а не под полноту: {amount}, "
            f"потому что {why}. Меньше риск — меньше процесса.")
    if provisional:
        line += (" Тяжесть пока не заявлена — если задача крупнее или опаснее, процесса станет больше.")
    return line
